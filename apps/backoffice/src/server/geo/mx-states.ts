/**
 * The 32 federal entities: name and outline, by their bare ISO 3166-2:MX
 * subdivision code — which is exactly what Vercel's
 * `x-vercel-ip-country-region` sends (measured 2026-09-22: `CHH` for
 * Chihuahua, not `MX-CHH`).
 *
 * ── Where the geometry comes from ───────────────────────────────────────────
 * Natural Earth `ne_10m_admin_1_states_provinces` (public domain, CC0 — no
 * attribution obligation; credited in THIRD_PARTY_LICENSES.md by that file's
 * voluntary convention). Converted **once, offline**; `mapshaper` runs through
 * `npx` and is deliberately not a dependency of any package.json:
 *
 *   npx mapshaper ne_10m_admin_1_states_provinces.geojson \
 *     -filter 'adm0_a3 === "MEX" && iso_3166_2 !== "MX-X01~"' \
 *     -each 'code = iso_3166_2 === "MX-DIF" ? "CMX" : iso_3166_2.replace("MX-", "")' \
 *     -filter-fields code \
 *     -filter-islands min-area=120000000 \
 *     -simplify 2PCT keep-shapes \
 *     -proj '+proj=lcc +lat_1=17.5 +lat_2=29.5 +lat_0=12 +lon_0=-102 \
 *            +x_0=2500000 +y_0=0 +ellps=GRS80' \
 *     -o mx.svg format=svg width=1000 id-field=code
 *
 * (`2PCT` above is literally `2` followed by a percent sign.)
 *
 * Two corrections that pipeline makes, either of which would otherwise show up
 * as a silently broken map:
 *
 * - Natural Earth still labels Mexico City **`MX-DIF`**, the code retired in
 *   2016. Vercel sends the current `CMX`, so DIF is remapped rather than left
 *   to miss every lookup.
 * - It also carries a nameless placeholder feature, `MX-X01~`, which is
 *   dropped — 33 features in, 32 states out.
 *
 * `-filter-islands` removes Quintana Roo's cays and Baja California Sur's
 * lagoon islets, which cost far more bytes than they show at this size. The
 * projection is the Lambert conformal conic Mexico is conventionally drawn in,
 * so the north is not stretched the way Mercator stretches it.
 *
 * ~10 KB of path data for the whole country, inside the RSC payload.
 */

