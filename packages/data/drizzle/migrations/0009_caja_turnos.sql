CREATE TABLE IF NOT EXISTS `caja_turnos` (
	`id` text PRIMARY KEY NOT NULL,
	`user_id` text NOT NULL,
	`fecha` text NOT NULL,
	`apertura_at` text NOT NULL,
	`cierre_at` text,
	`monto_apertura_centavos` numeric NOT NULL,
	`efectivo_adicional_centavos` numeric NOT NULL,
	`monto_cierre_centavos` numeric,
	`efectivo_esperado_centavos` numeric,
	`diferencia_centavos` numeric,
	`discrepancy_reason` text,
	`explicacion` text,
	`total_transferencias` numeric NOT NULL DEFAULT 0,
	`total_tarjeta` numeric NOT NULL DEFAULT 0,
	`total_qr` numeric NOT NULL DEFAULT 0,
	`total_credito` numeric NOT NULL DEFAULT 0,
	`egreso_auto_id` text,
	`business_id` text NOT NULL,
	`device_id` text NOT NULL,
	`created_by_user_id` text,
	`created_at` text NOT NULL,
	`updated_at` text NOT NULL,
	`deleted_at` text
);